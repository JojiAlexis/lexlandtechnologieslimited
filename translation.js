/**
 * Updates all elements with the [data-i18n] attribute
 * @param {string} lang - The selected language name
 */
function translatePage(lang) {
    requestAnimationFrame(() => {
        const elements = document.querySelectorAll('[data-i18n]');
        const dict = translations[lang];
        
        if (!dict) return;

        elements.forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (dict[key]) {
                el.innerHTML = dict[key];
            }
        });

        // Update data-i18n for the hero stats section if present
        const heroStats = document.querySelector('.hero-stats');
        if (heroStats) {
            heroStats.querySelectorAll('.stat-label').forEach(el => {
                const key = el.getAttribute('data-i18n');
                if (dict[key]) el.textContent = dict[key];
            });
        }
    });

    // Sync with any Alpine.js components on the page
    // Persist to local storage
    localStorage.setItem('lang', lang);
}

// --- Implementation to make the translation system work ---

document.addEventListener('DOMContentLoaded', () => {
    // 1. Get the language from local storage or set a default (e.g., 'English')
    let currentLang = localStorage.getItem('lang') || 'English';

    // 2. Apply translations on page load
    translatePage(currentLang);

    // 3. Set the language selector to the current language (if a selector exists)
    //    This assumes you have an HTML element with id="language-selector" (e.g., a <select> tag)
    const langSelector = document.getElementById('language-selector');
    if (langSelector) {
        langSelector.value = currentLang;

        // 4. Add an event listener to update translations when the language selection changes
        langSelector.addEventListener('change', (event) => {
            translatePage(event.target.value);
        });
    }
});